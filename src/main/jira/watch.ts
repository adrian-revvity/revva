/**
 * M6 comment watcher: polls Jira for new comments on tickets with a PR, excluding our own.
 *
 * The Atlassian MCP has no "list comments" tool, so comments come from getIssue's
 * fields.comment.comments. A watermark table records which comment ids we've already
 * surfaced; anything newer and not authored by us becomes a "new comments" alert.
 * "Tackle comments" runs a rework session in the worktree; its summary is posted back
 * to Jira as a reply comment and pushed to the open PR.
 */
import { BrowserWindow } from 'electron'
import { jiraMcp } from './mcp'
import { getDb } from '../db'
import { openCodeService, describeError } from '../opencode/service'
import { eventBus, type RawEvent } from '../opencode/bus'
import { shipManager } from '../ship'
import { workManager } from '../pipeline/works'
import { IPC, type JiraComment, type PushEvent } from '@shared/types'

const POLL_MS = 60_000
/** Comments revva itself posts are skipped, in addition to author matching. */
const REVVA_MARKERS = ['*revva*:', 'Generated by revva']

interface NewCommentRow {
  work_id: string
  ticket_key: string
  comment_id: string
  author: string
  body: string
  created_at: number
  seen_at: number
  tackled_at: number | null
}

function send(event: PushEvent): void {
  for (const win of BrowserWindow.getAllWindows()) win.webContents.send(IPC.eventPush, event)
}

function toComment(r: NewCommentRow): JiraComment {
  return {
    workId: r.work_id,
    ticketKey: r.ticket_key,
    id: r.comment_id,
    author: r.author,
    body: r.body,
    createdAt: r.created_at,
    tackledAt: r.tackled_at ?? undefined
  }
}

class CommentWatcher {
  private wired = false
  private timer: NodeJS.Timeout | undefined
  /** rework sessions: sessionId → workId */
  private reworking = new Map<string, string>()

  wire(): void {
    if (this.wired) return
    this.wired = true
    eventBus.on('event', (e: RawEvent) => this.onEvent(e))
    this.timer = setInterval(() => void this.poll().catch(() => undefined), POLL_MS)
    void this.poll().catch(() => undefined)
  }

  dispose(): void {
    clearInterval(this.timer)
  }

  /** Undismissed alerts (comments not yet tackled). */
  pending(): JiraComment[] {
    return (
      getDb()
        .prepare('SELECT * FROM jira_comment WHERE tackled_at IS NULL ORDER BY created_at ASC')
        .all() as NewCommentRow[]
    ).map(toComment)
  }

  newCount(): number {
    return this.pending().length
  }

  /** One poll pass: every work with a PR (or shipped) gets its ticket's comments checked. */
  async poll(): Promise<void> {
    if (!jiraMcp.connected) return
    const works = getDb()
      .prepare("SELECT id, ticket_key FROM work WHERE state = 'SHIPPED' OR pr_url IS NOT NULL")
      .all() as Array<{ id: string; ticket_key: string }>
    if (works.length === 0) return
    const me = await jiraMcp.myAccountId().catch(() => undefined)
    let changed = false

    for (const w of works) {
      let comments: Array<{ id?: string; author?: { displayName?: string; accountId?: string }; body?: unknown; created?: string }> = []
      try {
        comments = await jiraMcp.comments(w.ticket_key)
      } catch {
        continue // transient MCP failure — next tick retries
      }
      for (const c of comments) {
        const id = String(c.id ?? '')
        if (!id) continue
        const body = extractText(c.body)
        const mine =
          (!!me && c.author?.accountId === me) || REVVA_MARKERS.some((m) => body.includes(m))
        if (mine) continue
        const res = getDb()
          .prepare(
            `INSERT OR IGNORE INTO jira_comment(work_id, ticket_key, comment_id, author, body, created_at, seen_at)
             VALUES(?,?,?,?,?,?,?)`
          )
          .run(w.id, w.ticket_key, id, c.author?.displayName ?? 'unknown', body, Date.parse(c.created ?? '') || Date.now(), Date.now())
        if (res.changes > 0) changed = true
      }
    }
    if (changed) this.pushPending()
  }

  /** Rework: one session per alerted work; the transcript lives in OpenCode. */
  async tackleComments(workId: string): Promise<void> {
    const work = getDb()
      .prepare('SELECT * FROM work WHERE id = ?')
      .get(workId) as
      | { id: string; ticket_key: string; branch: string; worktree_dir: string; pr_url: string | null }
      | undefined
    if (!work) throw new Error('Work not found.')
    const pending = this.pending().filter((c) => c.workId === workId)
    if (pending.length === 0) throw new Error('No new comments to tackle.')
    if (this.reworking.size > 0 && [...this.reworking.values()].includes(workId)) throw new Error('Already reworking.')

    const api = openCodeService.api
    const session = await api.session.create({
      title: `${work.ticket_key} · rework (${pending.length} comment(s))`,
      location: { directory: work.worktree_dir },
      metadata: { revva: { kind: 'rework', workId } }
    })
    this.reworking.set(session.id, workId)
    getDb().prepare('UPDATE work SET session_id = ?, updated_at = ? WHERE id = ?').run(session.id, Date.now(), workId)
    workManager.setReviewState(workId, 'REWORK')
    const prompt = [
      `Ticket ${work.ticket_key} received new Jira comments after the PR was opened (${work.pr_url ?? 'see branch'}).`,
      `Worktree: ${work.worktree_dir} (branch ${work.branch}). Address the feedback below: change code where needed, commit (do not push — revva pushes).`,
      'Then write a short reply per comment, under a final section headed "REVVA-REPLY" (plain markdown, one bullet per comment).',
      '',
      '--- New Jira comments ---',
      ...pending.map((c) => `[${c.author}] ${c.body}`),
      '--- End comments ---'
    ].join('\n')
    await api.session.prompt({ sessionID: session.id, text: prompt })
  }

  private onEvent(e: RawEvent): void {
    const data = (e.data ?? {}) as Record<string, unknown>
    const sessionId = data.sessionID
    if (typeof sessionId !== 'string') return
    const workId = this.reworking.get(sessionId)
    if (!workId) return

    switch (e.type) {
      case 'session.text.delta':
        for (const win of BrowserWindow.getAllWindows()) {
          win.webContents.send(IPC.eventPush, {
            kind: 'work.delta',
            workId,
            sessionId,
            messageId: String(data.assistantMessageID ?? ''),
            text: String(data.delta ?? '')
          })
        }
        break
      case 'session.execution.succeeded':
        this.reworking.delete(sessionId)
        void this.finishRework(workId, sessionId)
        break
      case 'session.execution.failed':
      case 'session.execution.interrupted':
        this.reworking.delete(sessionId)
        workManager.setReviewState(workId, 'WAITING_HUMAN')
        break
    }
  }

  /** Push fixes onto the PR branch, post the agent's reply to Jira, clear the alerts. */
  private async finishRework(workId: string, sessionId: string): Promise<void> {
    const work = getDb().prepare('SELECT * FROM work WHERE id = ?').get(workId) as
      | { id: string; ticket_key: string; branch: string; worktree_dir: string; pr_url: string | null }
      | undefined
    if (!work) return
    try {
      // Agent's reply section → one Jira comment quoting what was tackled.
      const messages = await openCodeService.api.message.list({ sessionID: sessionId, order: 'asc', limit: 200 })
      const last = [...messages.data].reverse().find((m) => m.type === 'assistant')
      let text = ''
      for (const part of (last as { content?: unknown[] })?.content ?? []) {
        const p = part as Record<string, unknown>
        if (p.type === 'text' && typeof p.text === 'string') text += p.text
      }
      const reply = text.split(/REVVA-REPLY/i)[1]?.trim() ?? text.slice(-1500)
      await jiraMcp.addComment(
        work.ticket_key,
        `*revva*: reworked feedback — ${work.pr_url ?? work.branch}\n\n${reply.slice(0, 4000)}`
      )
      await shipManager.pushOnly(work.worktree_dir, work.branch)
      getDb().prepare('UPDATE jira_comment SET tackled_at = ? WHERE work_id = ? AND tackled_at IS NULL').run(Date.now(), workId)
      getDb().prepare('UPDATE work SET session_id = ?, updated_at = ? WHERE id = ?').run(sessionId, Date.now(), workId)
      workManager.setReviewState(workId, 'SHIPPED')
    } catch (err) {
      console.warn('[watch] rework finish failed:', describeError(err))
      workManager.setReviewState(workId, 'WAITING_HUMAN')
    }
    this.pushPending()
  }

  private pushPending(): void {
    send({ kind: 'comments', items: this.pending() })
  }
}

/** Jira comment bodies are ADF or markdown depending on the tool; extract plain text. */
function extractText(body: unknown): string {
  if (typeof body === 'string') return body
  const texts: string[] = []
  const walk = (n: unknown): void => {
    if (Array.isArray(n)) return void n.forEach(walk)
    if (n && typeof n === 'object') {
      const o = n as Record<string, unknown>
      if (typeof o.text === 'string') texts.push(o.text)
      if (o.content) walk(o.content)
    }
  }
  walk(body)
  return texts.join(' ').trim()
}

export const commentWatcher = new CommentWatcher()
